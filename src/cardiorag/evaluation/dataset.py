"""Loading the hand-authored evaluation dataset (data/evaluation/eval_dataset.jsonl).

The dataset itself is not generated by this module - it was authored by
reading the actual corpus (see scripts/generate_eval_dataset.py's docstring)
and is version-controlled as data. This module only parses and validates
its structure.
"""

import json
from pathlib import Path

from cardiorag.models import EvaluationExample


def load_evaluation_dataset(path: Path) -> list[EvaluationExample]:
    with open(path, encoding="utf-8") as f:
        return [EvaluationExample.model_validate(json.loads(line)) for line in f if line.strip()]
